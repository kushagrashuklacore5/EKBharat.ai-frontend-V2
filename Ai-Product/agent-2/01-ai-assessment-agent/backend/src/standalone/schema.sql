-- Standalone schema for the AI Assessment Agent.
-- Extracted from the LMS PostgreSQL migration (001_initial_schema.sql + 003): only the tables the
-- assessment adapter reads (a minimal school directory: universities, users, classrooms, memberships,
-- teaching assignments, courses) and the module's own aia_* tables. Runs on embedded PostgreSQL
-- (PGlite) by default, or on any PostgreSQL 14+ server.

CREATE OR REPLACE FUNCTION utc_now_text(shift interval DEFAULT interval '0') RETURNS text
  LANGUAGE sql STABLE AS $$ SELECT to_char((now() AT TIME ZONE 'UTC') + shift, 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE aia_assessment_recipients (
  assessment_id BIGINT NOT NULL,
  university_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  PRIMARY KEY (assessment_id, student_id)
);

CREATE TABLE aia_assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL,
  teacher_id BIGINT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  subject TEXT NOT NULL,
  classroom_id BIGINT,
  duration_minutes BIGINT,
  status TEXT NOT NULL DEFAULT 'draft',
  source TEXT NOT NULL DEFAULT 'manual',
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  published_at TEXT,
  opens_at TEXT,
  closes_at TEXT,
  closed_at TEXT,
  course_id BIGINT,
  CHECK (duration_minutes IS NULL OR (duration_minutes BETWEEN 1 AND 600)),
  CHECK (status IN ('draft', 'published')),
  CHECK (source IN ('manual'))
);

CREATE TABLE aia_assignment_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL,
  position BIGINT NOT NULL,
  text TEXT NOT NULL,
  max_marks BIGINT NOT NULL,
  image_key TEXT,
  UNIQUE (assignment_id, position),
  CHECK (position >= 1),
  CHECK (max_marks BETWEEN 1 AND 1000)
);

CREATE TABLE aia_assignment_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL,
  assignment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'submitted',
  storage_key TEXT NOT NULL,
  original_filename TEXT NOT NULL,
  file_size BIGINT NOT NULL,
  content_type TEXT NOT NULL DEFAULT 'application/pdf',
  sha256 TEXT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  submitted_at TEXT NOT NULL,
  ai_marks DOUBLE PRECISION,
  ai_grade TEXT,
  ai_feedback TEXT,
  ai_question_marks_json TEXT,
  ai_limitations_json TEXT,
  ai_evaluated_at TEXT,
  final_marks DOUBLE PRECISION,
  final_grade TEXT,
  teacher_feedback TEXT,
  final_question_marks_json TEXT,
  evaluated_at TEXT,
  evaluated_by BIGINT,
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  UNIQUE (storage_key),
  UNIQUE (assignment_id, student_id),
  CHECK (status IN ('submitted', 'evaluated')),
  CHECK (file_size > 0),
  CHECK (content_type = 'application/pdf'),
  CHECK (version >= 1),
  CHECK ((status = 'evaluated') = (final_marks IS NOT NULL))
);

CREATE TABLE aia_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL,
  teacher_id BIGINT NOT NULL,
  classroom_id BIGINT NOT NULL,
  title TEXT NOT NULL,
  instructions TEXT NOT NULL DEFAULT '',
  max_marks BIGINT NOT NULL,
  due_at TEXT,
  status TEXT NOT NULL DEFAULT 'draft',
  published_at TEXT,
  closed_at TEXT,
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  CHECK (max_marks BETWEEN 1 AND 1000),
  CHECK (status IN ('draft', 'published', 'closed'))
);

CREATE TABLE aia_attempt_answers (
  attempt_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  option_position BIGINT NOT NULL,
  is_correct BIGINT,
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  PRIMARY KEY (attempt_id, question_id),
  CHECK (option_position BETWEEN 0 AND 3),
  CHECK (is_correct IS NULL OR is_correct IN (0, 1))
);

CREATE TABLE aia_attempt_archive (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_attempt_id BIGINT NOT NULL,
  university_id BIGINT NOT NULL,
  assessment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  status TEXT NOT NULL,
  started_at TEXT NOT NULL,
  deadline_at TEXT,
  finished_at TEXT NOT NULL,
  total_questions BIGINT NOT NULL,
  attempted BIGINT NOT NULL,
  correct BIGINT NOT NULL,
  incorrect BIGINT NOT NULL,
  unattempted BIGINT NOT NULL,
  score BIGINT NOT NULL,
  percentage DOUBLE PRECISION NOT NULL,
  answers_json TEXT NOT NULL,
  reset_by BIGINT NOT NULL,
  reset_at TEXT NOT NULL,
  UNIQUE (original_attempt_id),
  CHECK (status IN ('submitted', 'expired'))
);

CREATE TABLE aia_attempt_responses (
  attempt_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  selected_positions TEXT,
  numeric_value TEXT,
  is_correct BIGINT,
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  PRIMARY KEY (attempt_id, question_id),
  CHECK (is_correct IS NULL OR is_correct IN (0, 1)),
  CHECK ((selected_positions IS NULL) <> (numeric_value IS NULL))
);

CREATE TABLE aia_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL,
  assessment_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'in_progress',
  started_at TEXT NOT NULL,
  deadline_at TEXT,
  finished_at TEXT,
  total_questions BIGINT,
  attempted BIGINT,
  correct BIGINT,
  incorrect BIGINT,
  unattempted BIGINT,
  score BIGINT,
  percentage DOUBLE PRECISION,
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  UNIQUE (assessment_id, student_id),
  CHECK (status IN ('in_progress', 'submitted', 'expired')),
  CHECK ((status = 'in_progress') = (finished_at IS NULL))
);

CREATE TABLE aia_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL,
  position BIGINT NOT NULL,
  text TEXT NOT NULL,
  is_correct BIGINT NOT NULL DEFAULT 0,
  UNIQUE (question_id, position),
  CHECK (position BETWEEN 0 AND 3),
  CHECK (is_correct IN (0, 1))
);

CREATE TABLE aia_performance_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL,
  teacher_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  focus_label TEXT NOT NULL,
  content_json TEXT NOT NULL,
  preview_json TEXT,
  scope_json TEXT NOT NULL,
  generated_at TEXT NOT NULL,
  shared_at TEXT,
  shared_by BIGINT,
  read_at TEXT,
  created_at TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE TABLE aia_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL,
  position BIGINT NOT NULL,
  text TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT utc_now_text(),
  updated_at TEXT NOT NULL DEFAULT utc_now_text(),
  explanation TEXT NOT NULL DEFAULT '',
  difficulty TEXT,
  question_type TEXT NOT NULL DEFAULT 'single_mcq',
  numeric_answer TEXT,
  numeric_format TEXT,
  image_key TEXT,
  CHECK (position >= 1),
  CHECK (difficulty IS NULL OR difficulty IN ('easy', 'medium', 'hard')),
  CHECK (question_type IN ('single_mcq', 'multi_select', 'numerical')),
  CHECK (numeric_format IS NULL OR numeric_format IN ('integer', 'decimal'))
);

CREATE TABLE classroomAssignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classroomId BIGINT NOT NULL,
  teacherId BIGINT NOT NULL,
  role TEXT NOT NULL DEFAULT 'class_teacher',
  assignedAt TEXT DEFAULT utc_now_text()
);

CREATE TABLE classrooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id BIGINT NOT NULL DEFAULT 1,
  name TEXT NOT NULL,
  grade TEXT NOT NULL,
  section TEXT,
  classTeacher TEXT,
  classTeacherId BIGINT,
  studentCount BIGINT DEFAULT 0,
  timetable TEXT,
  createdAt TEXT DEFAULT utc_now_text()
);

CREATE TABLE course_classrooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  courseId BIGINT NOT NULL,
  classroomId BIGINT NOT NULL,
  assignedBy BIGINT,
  enrollAll BIGINT NOT NULL DEFAULT 1,
  createdAt TEXT DEFAULT utc_now_text(),
  UNIQUE (courseId, classroomId)
);

CREATE TABLE course_students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  courseId BIGINT NOT NULL,
  studentId BIGINT NOT NULL,
  createdAt TEXT DEFAULT utc_now_text(),
  enrolledViaClassroomId BIGINT,
  UNIQUE (courseId, studentId)
);

CREATE TABLE courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  mentorId BIGINT,
  classroomId BIGINT,
  category TEXT,
  -- declared INTEGER in SQLite, but the app stores text such as '8 Weeks' / '1 year'
  duration TEXT,
  price DOUBLE PRECISION DEFAULT 0,
  university_id BIGINT DEFAULT 1,
  createdAt TEXT DEFAULT utc_now_text()
);

CREATE TABLE student_classroom_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studentId BIGINT NOT NULL,
  classroomId BIGINT NOT NULL,
  createdAt TEXT DEFAULT utc_now_text(),
  UNIQUE (studentId, classroomId)
);

CREATE TABLE universities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  area TEXT NOT NULL,
  adminId BIGINT,
  subscriptionPlan TEXT DEFAULT 'free',
  createdAt TEXT DEFAULT utc_now_text(),
  updatedAt TEXT DEFAULT utc_now_text()
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  password TEXT NOT NULL,
  role TEXT NOT NULL,
  university_id BIGINT DEFAULT 1,
  isApproved SMALLINT DEFAULT 0,
  classroom_id BIGINT,
  subscriptionPlan TEXT DEFAULT 'free',
  createdAt TEXT DEFAULT utc_now_text(),
  updatedAt TEXT DEFAULT utc_now_text(),
  created_at TEXT,
  updated_at TEXT,
  created_by BIGINT,
  sessions_valid_from BIGINT,
  UNIQUE (email)
);

CREATE INDEX idx_aia_assessment_recipients_student ON aia_assessment_recipients (university_id, student_id);

