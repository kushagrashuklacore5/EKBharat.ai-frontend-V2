import { useState } from 'react'
import { AlertTriangle, Loader2, Sparkles } from 'lucide-react'
import { generateWorkflow } from './engine/generator'
import { studioBus } from './studioBus'
import { ApiError, generateWithGroq } from './aiClient'
import type { Workflow } from './engine/types'

const EXAMPLES = [
  'Find potential customers for our AI services and qualify them.',
  'When a WhatsApp message arrives, extract customer details and save them to CRM.',
  'Read GST invoices, extract details and request manager approval.',
  'Collect leads from forms, classify them and send notifications.',
  'Generate a daily report from pending customer support tickets.',
]

const FLOW = ['Describe', 'Generate with AI', 'Review on canvas', 'Approve', 'Run or email']

type State =
  | { s: 'idle' }
  | { s: 'loading'; prompt: string }
  | { s: 'done'; wf: Workflow }
  | { s: 'error'; message: string; details: string[]; prompt: string }

/** "Describe your workflow" — Groq generates a registry-valid workflow that loads onto the Studio canvas. */
export function WorkflowGenerator() {
  const [text, setText] = useState('')
  const [st, setSt] = useState<State>({ s: 'idle' })
  const busy = st.s === 'loading'

  const show = (wf: Workflow) => {
    setSt({ s: 'done', wf })
    studioBus.emit({ kind: 'workflow', workflow: wf })
    document.getElementById('studio-canvas')?.scrollIntoView({ behavior: 'smooth', block: 'start' })
  }

  const generate = async (prompt: string) => {
    const p = prompt.trim()
    if (!p || busy) return
    setSt({ s: 'loading', prompt: p })
    try {
      const { workflow } = await generateWithGroq(p)
      show(workflow)
    } catch (e) {
      setSt({ s: 'error', message: e instanceof Error ? e.message : String(e), details: e instanceof ApiError ? e.details : [], prompt: p })
    }
  }

  /** Offline fallback: the earlier keyword-based generator, clearly labelled. */
  const fallback = (prompt: string) => {
    const { workflow, understood } = generateWorkflow(prompt)
    workflow.ai = {
      prompt,
      model: 'rule-based generator',
      provider: 'rules',
      summary: workflow.description,
      steps: understood,
      purpose: /lead|prospect|customer/i.test(prompt) ? 'lead_generation' : 'general',
      missing: [],
      warnings: ['Generated by keyword rules, not by AI. Review every step.'],
      generatedAt: Date.now(),
    }
    show(workflow)
  }

  const step = st.s === 'idle' ? 0 : st.s === 'loading' ? 1 : st.s === 'error' ? 1 : 2

  return (
    <div className="panel p-4 sm:p-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="flex items-center gap-2 text-[1.15rem] font-semibold text-fg">
            <Sparkles size={17} className="text-saffron" /> Describe your workflow
          </h2>
          <p className="mt-1 max-w-2xl text-[13.5px] leading-relaxed text-muted">
            Say what you want to automate in plain language. AI builds the workflow on the canvas below; you review it, approve it, then run it or email it.
          </p>
        </div>
        <span className="rounded bg-[#e3f0f6] px-2 py-1 text-[11px] font-bold text-cyan" title="Generated by an LLM on Groq through our server, then validated against the Workflow Studio node library">
          Powered by Groq AI
        </span>
      </div>

      <ol className="mt-4 flex flex-wrap gap-x-1 gap-y-1.5 text-[11.5px] font-semibold" aria-label="Steps">
        {FLOW.map((f, i) => (
          <li key={f} className="flex items-center gap-1">
            <span className={`grid size-5 place-items-center rounded-full text-[10.5px] ${i <= step ? 'bg-teal text-white' : 'bg-ink-850 text-faint shadow-[inset_0_0_0_1px_var(--color-line)]'}`}>{i + 1}</span>
            <span className={i <= step ? 'text-fg' : 'text-faint'}>{f}</span>
            {i < FLOW.length - 1 && <span className="mx-1 text-faint">›</span>}
          </li>
        ))}
      </ol>

      <form
        className="mt-4 flex flex-col gap-2 sm:flex-row"
        onSubmit={(e) => {
          e.preventDefault()
          void generate(text)
        }}
      >
        <label className="sr-only" htmlFor="wf-prompt">
          Describe your workflow
        </label>
        <textarea
          id="wf-prompt"
          value={text}
          onChange={(e) => setText(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) void generate(text)
          }}
          rows={2}
          maxLength={2000}
          disabled={busy}
          placeholder={EXAMPLES[0]}
          className="min-h-[52px] flex-1 resize-y rounded-lg bg-ink-850 px-3 py-2.5 text-[14px] text-fg shadow-[inset_0_0_0_1px_var(--color-line-strong)] placeholder:text-faint focus:shadow-[inset_0_0_0_1.5px_var(--color-cyan)] focus:outline-none disabled:opacity-60"
        />
        <button type="submit" disabled={!text.trim() || busy} className="inline-flex h-11 items-center justify-center gap-2 rounded-lg bg-fg px-4 text-[14px] font-semibold text-ink-950 hover:bg-electric hover:text-white disabled:opacity-45 sm:h-auto">
          {busy ? <Loader2 size={15} className="animate-spin" /> : <Sparkles size={15} />} {busy ? 'Generating…' : 'Generate'}
        </button>
      </form>

      <div className="mt-3 flex flex-wrap gap-1.5">
        {EXAMPLES.map((ex) => (
          <button
            key={ex}
            type="button"
            disabled={busy}
            onClick={() => (setText(ex), void generate(ex))}
            className="rounded-full bg-ink-850 px-2.5 py-1 text-left text-[12px] text-fg-soft shadow-[inset_0_0_0_1px_var(--color-line)] hover:shadow-[inset_0_0_0_1px_var(--color-cyan)] disabled:opacity-50"
          >
            {ex}
          </button>
        ))}
      </div>

      <div aria-live="polite">
        {st.s === 'loading' && (
          <div className="mt-4 flex items-center gap-2.5 rounded-lg bg-ink-850 p-3 text-[13px] text-fg-soft">
            <Loader2 size={15} className="animate-spin text-cyan" /> Designing your workflow with Groq AI and checking it against the node library… this usually takes 5–20 seconds.
          </div>
        )}
        {st.s === 'error' && (
          <div className="mt-4 rounded-lg bg-[#f9e4e4] p-3 text-[13px] text-[#8a2f2f]" role="alert">
            <p className="flex items-center gap-1.5 font-bold">
              <AlertTriangle size={14} /> {st.message}
            </p>
            {st.details.length > 0 && (
              <ul className="mt-1.5 list-disc pl-5 text-[12px]">
                {st.details.slice(0, 6).map((d) => (
                  <li key={d}>{d}</li>
                ))}
              </ul>
            )}
            <div className="mt-2.5 flex flex-wrap gap-2">
              <button type="button" onClick={() => void generate(st.prompt)} className="rounded-md bg-danger px-3 py-1.5 text-[12.5px] font-semibold text-white">
                Try again
              </button>
              <button type="button" onClick={() => fallback(st.prompt)} className="rounded-md px-3 py-1.5 text-[12.5px] font-semibold text-[#8a2f2f] shadow-[inset_0_0_0_1px_rgb(138_47_47/.35)]">
                Use the basic rule-based generator instead
              </button>
            </div>
          </div>
        )}
        {st.s === 'done' && st.wf.ai && (
          <div className="mt-4 rounded-lg bg-ink-850 p-3" role="status">
            <p className="text-[12px] font-bold text-faint">
              Added to the canvas as “{st.wf.name}” · {st.wf.ai.provider === 'groq' ? `Groq · ${st.wf.ai.model}` : 'rule-based generator'}
            </p>
            <p className="mt-1 text-[13.5px] leading-relaxed text-fg-soft">{st.wf.ai.summary}</p>
            {st.wf.ai.steps.length > 0 && (
              <ol className="mt-2 list-decimal space-y-0.5 pl-5 text-[13px] text-fg-soft">
                {st.wf.ai.steps.map((s) => (
                  <li key={s}>{s}</li>
                ))}
              </ol>
            )}
            {st.wf.ai.missing.length > 0 && (
              <p className="mt-2 text-[12.5px] text-amber">
                Needs your input: {[...new Set(st.wf.ai.missing.map((m) => m.what))].slice(0, 5).join(' · ')}
              </p>
            )}
            <p className="mt-2 text-[12px] text-muted">Next: review the steps on the canvas, edit anything, then press “Approve this workflow”.</p>
          </div>
        )}
      </div>
    </div>
  )
}
